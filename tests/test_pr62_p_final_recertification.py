def test_exact_departures_endpoints_regimes_protection_and_tails() -> None:
    for route_id, expected in _EXPECTED.items():
        route = _payload()["routes"][route_id]
        for direction, trip_total in zip(("outbound", "inbound"), expected["trips"], strict=True):
            item = route["directions"][direction]
            departures = item["exact_departures"]
            assert len(departures) == trip_total
            assert departures[0] == item["authoritative_first_departure"]
            assert departures[-1] == item["authoritative_last_departure"]
            assert all(value % 60 == 0 for value in departures)
            assert all(a < b for a, b in zip(departures, departures[1:], strict=False))
            assert [
                value for regime in item["service_regimes"] for value in regime["departures"]
            ] == departures
            for regime in item["service_regimes"]:
                gaps = [
                    (b - a) // 60
                    for a, b in zip(regime["departures"], regime["departures"][1:], strict=False)
                ]
                assert not gaps or set(gaps) == {regime["uniform_headway_minutes"]}
            assert item["protection_passed"] is True
            assert item["tail_ordering"]["eligible"] is True
            assert item["compilation_fingerprint"]
        assert route["settlement_used"] is False
        assert route["selected_timetable_manually_edited"] is False


