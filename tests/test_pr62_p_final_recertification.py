def test_workbooks_match_selected_vectors_fleet_universe_and_sheet_order() -> None:
    for route_id, expected in _EXPECTED.items():
        route = _payload()["routes"][route_id]
        workbook = load_workbook(
            _ROOT / route["workbook"]["path"], data_only=False, keep_links=True
        )
        assert workbook.sheetnames == _SHEETS[route_id]
        assert not workbook._external_links
        summary = workbook["Summary"]
        summary_values = {
            summary.cell(row=row, column=1).value: summary.cell(row=row, column=2).value
            for row in range(3, summary.max_row + 1)
        }
        assert summary_values["Selected pair fingerprint"] == expected["selected"]
        assert summary_values["Certification status"] == "PILOT_FINAL_RECERTIFIED_V2"
        timetable = workbook["Timetable"]
        for direction, column in (("outbound", 2), ("inbound", 7)):
            departures = route["directions"][direction]["exact_departures"]
            assert [
                _seconds(timetable.cell(row=index + 2, column=column).value)
                for index in range(len(departures))
            ] == departures
        fleet = workbook["Fleet_Plan"]
        assert [fleet.cell(row=row, column=2).value for row in range(2, fleet.max_row + 1)] == [
            item["trip_id"] for item in route["fleet_plan"]["assignments"]
        ]


